using Microsoft.EntityFrameworkCore;
using NamelyzeEcom.Data.Context;
using NamelyzeEcom.Data.Entities;
using NamelyzeEcom.Data.Repositories.Interfaces;
using System.Linq.Expressions;

namespace NamelyzeEcom.Data.Repositories;

public class Repository<T> : IRepository<T> where T : BaseEntity
{
    protected readonly NamelyzeEcomContext _context;
    protected readonly DbSet<T> _dbSet;

    public Repository(NamelyzeEcomContext context)
    {
        _context = context;
        _dbSet = context.Set<T>();
    }

    public async Task<T?> GetByIdAsync(int id)
    {
        return await _dbSet.FindAsync(id);
    }

    public async Task<IEnumerable<T>> GetAllAsync()
    {
        return await _dbSet.ToListAsync();
    }

    public async Task<IEnumerable<T>> FindAsync(Expression<Func<T, bool>> predicate)
    {
        return await _dbSet.Where(predicate).ToListAsync();
    }

    public async Task<T> AddAsync(T entity)
    {
        await _dbSet.AddAsync(entity);
        await _context.SaveChangesAsync();
        return entity;
    }

    public async Task UpdateAsync(T entity)
    {
        entity.UpdatedAt = DateTime.UtcNow;
        _dbSet.Update(entity);
        await _context.SaveChangesAsync();
    }

    public async Task DeleteAsync(int id)
    {
        var entity = await GetByIdAsync(id);
        if (entity != null)
        {
            entity.IsDeleted = true;
            entity.UpdatedAt = DateTime.UtcNow;
            await _context.SaveChangesAsync();
        }
    }
}
